-- Служебные таблицы: версии снимков, настройки модели, пользователи, сессии.
CREATE TABLE public.snapshots (
    version bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    as_of timestamptz,
    loaded_at timestamptz NOT NULL DEFAULT now(),
    source text NOT NULL
);

CREATE TABLE public.model_settings (
    version bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body jsonb NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by text NOT NULL
);

CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role text NOT NULL CHECK (role IN ('analyst', 'viewer')),
    totp_secret text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.sessions (
    token_hash text PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    csrf_token text NOT NULL,
    expires_at timestamptz NOT NULL
);

CREATE INDEX sessions_user_id_idx ON public.sessions (user_id);

