-- Задачи удержания: кого из клиентов взяли в работу. Внешнего ключа на таблицы снимка нет:
-- снимок заменяется целиком, а задача живёт дальше.
CREATE TABLE public.retention_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL,
    customer_email text NOT NULL,
    status text NOT NULL CHECK (status IN ('in_work', 'contacted', 'postponed', 'closed')),
    outcome text CHECK (outcome IN ('renewed', 'refused', 'no_answer', 'not_needed')),
    assignee text NOT NULL,
    due_at timestamptz NOT NULL,
    note text NOT NULL DEFAULT '',
    version bigint NOT NULL DEFAULT 1,
    baseline jsonb NOT NULL,
    created_by text NOT NULL,
    created_at timestamptz NOT NULL,
    updated_by text NOT NULL,
    updated_at timestamptz NOT NULL,
    closed_at timestamptz,
    CHECK ((status = 'closed') = (outcome IS NOT NULL))
);

-- Одна открытая задача на клиента: гонку двух «взять в работу» решает этот индекс.
CREATE UNIQUE INDEX retention_tasks_one_open_idx ON public.retention_tasks (customer_id) WHERE status <> 'closed';
CREATE INDEX retention_tasks_updated_idx ON public.retention_tasks (updated_at DESC, id DESC);
CREATE INDEX retention_tasks_customer_idx ON public.retention_tasks (customer_id);

CREATE TABLE public.retention_task_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES public.retention_tasks(id) ON DELETE CASCADE,
    at timestamptz NOT NULL,
    actor text NOT NULL,
    kind text NOT NULL CHECK (kind IN ('created', 'changed', 'contact', 'note')),
    channel text CHECK (channel IN ('email', 'phone', 'messenger', 'other')),
    text text NOT NULL DEFAULT '',
    changes jsonb NOT NULL DEFAULT '[]'
);

CREATE INDEX retention_task_events_task_idx ON public.retention_task_events (task_id, id);

