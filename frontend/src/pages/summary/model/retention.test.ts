import { clients, highWithoutTaskText, inWorkText } from './retention';

describe('текст блока «Работа с клиентами»', () => {
  it('склоняет клиентов', () => {
    expect([1, 2, 5, 11, 21, 22].map(clients)).toEqual([
      '1 клиент',
      '2 клиента',
      '5 клиентов',
      '11 клиентов',
      '21 клиент',
      '22 клиента',
    ]);
  });
  it('на наборе организаторов: клиент 9 в работе', () => {
    expect(inWorkText(1, 318910, 359907)).toBe(
      'В работе 1 клиент · 3 189,10 € из 3 599,07 € ожидаемой потери (89 %)',
    );
  });
  it('без ожидаемой потери процент не пишется', () => {
    expect(inWorkText(0, 0, 0)).toBe('В работе 0 клиентов · 0,00 € из 0,00 € ожидаемой потери');
  });
  it('высокий риск без работы', () => {
    expect(highWithoutTaskText(2, 30000)).toBe('Высокий риск без работы: 2 клиента · 300,00 €');
  });
});
